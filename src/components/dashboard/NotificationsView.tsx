import React, { useState } from 'react';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '../ui/card';
import { Button } from '../ui/button';
import { Badge } from '../ui/badge';
import { useToast } from '../ui/toast-provider';
import { Bell, Check, Trash2, Shield, CreditCard, UserPlus, AlertCircle } from 'lucide-react';

interface NotificationRecord {
  id: string;
  title: string;
  description: string;
  time: string;
  read: boolean;
  type: 'billing' | 'security' | 'user' | 'system';
}

const INITIAL_NOTIFICATIONS: NotificationRecord[] = [
  { id: '1', title: 'Stripe payout processed', description: 'Monthly payout of $18,450.00 transferred to Chase Checking.', time: '10m ago', read: false, type: 'billing' },
  { id: '2', title: 'New developer access token generated', description: 'Token generated by Sarah Jenkins for automated CI deployment.', time: '1h ago', read: false, type: 'security' },
  { id: '3', title: 'New user joined enterprise team', description: 'Marcus Vance accepted your workspace invitation.', time: '3h ago', read: false, type: 'user' },
  { id: '4', title: 'API rate limit threshold warning', description: 'Traffic reached 82% of allocated tier ceiling at 14:00 UTC.', time: 'Yesterday', read: true, type: 'system' },
  { id: '5', title: 'SOC-2 audit renewal finalized', description: 'Compliance certificates uploaded to security vault.', time: '2 days ago', read: true, type: 'security' },
];

export const NotificationsView: React.FC = () => {
  const { showToast } = useToast();
  const [items, setItems] = useState<NotificationRecord[]>(INITIAL_NOTIFICATIONS);

  const markAllRead = () => {
    setItems((prev) => prev.map((n) => ({ ...n, read: true })));
    showToast('All notifications marked as read', undefined, 'info');
  };

  const clearAll = () => {
    setItems([]);
    showToast('Activity center cleared', undefined, 'info');
  };

  return (
    <div className="space-y-6">
      <Card>
        <CardHeader className="flex flex-row items-center justify-between pb-4">
          <div>
            <CardTitle>Activity Center &amp; Alerts</CardTitle>
            <CardDescription>System events, billing notifications, and security audit log</CardDescription>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" size="sm" onClick={markAllRead} className="h-8 gap-1.5 text-xs">
              <Check className="w-3.5 h-3.5" />
              <span>Mark all read</span>
            </Button>
            <Button variant="ghost" size="sm" onClick={clearAll} className="h-8 gap-1.5 text-xs text-rose-600">
              <Trash2 className="w-3.5 h-3.5" />
              <span>Clear</span>
            </Button>
          </div>
        </CardHeader>
        <CardContent className="space-y-2.5">
          {items.length === 0 ? (
            <div className="p-8 text-center text-xs text-zinc-500">
              No active notifications. You are all caught up!
            </div>
          ) : (
            items.map((n) => (
              <div
                key={n.id}
                className={`flex items-start gap-3 p-3.5 rounded-xl border text-xs transition-colors ${
                  !n.read
                    ? 'border-indigo-100 dark:border-indigo-900/60 bg-indigo-50/20 dark:bg-indigo-950/20'
                    : 'border-zinc-200 dark:border-zinc-800'
                }`}
              >
                <div className="p-2 rounded-lg bg-zinc-100 dark:bg-zinc-800 shrink-0 mt-0.5">
                  {n.type === 'billing' && <CreditCard className="w-4 h-4 text-emerald-600" />}
                  {n.type === 'security' && <Shield className="w-4 h-4 text-indigo-600" />}
                  {n.type === 'user' && <UserPlus className="w-4 h-4 text-blue-600" />}
                  {n.type === 'system' && <AlertCircle className="w-4 h-4 text-amber-600" />}
                </div>

                <div className="flex-1">
                  <div className="flex items-center justify-between">
                    <span className="font-semibold text-zinc-900 dark:text-zinc-100">{n.title}</span>
                    <span className="text-[11px] text-zinc-400 font-mono">{n.time}</span>
                  </div>
                  <p className="text-zinc-500 dark:text-zinc-400 mt-0.5 leading-relaxed">{n.description}</p>
                </div>
              </div>
            ))
          )}
        </CardContent>
      </Card>
    </div>
  );
};
